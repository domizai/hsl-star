// Keeps the generated parts of the library files in step with their sources:
// the version from package.json in the first line of hsl-star.js and
// hsl-star.glsl, and the OKLab hue table in hsl-star.glsl from hsl-star.js,
// so the shader can't drift from the library. Run it after changing the
// version or the hue axis:
//
//   npm run sync

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { toHsvHue } from '../js/hsl-star.js';

const path = (relative) => fileURLToPath(new URL(relative, import.meta.url));
const { version: VERSION } = JSON.parse(readFileSync(path('../package.json'), 'utf8'));
export const FILES = { js: path('../js/hsl-star.js'), glsl: path('../glsl/hsl-star.glsl') };

// --- Version --------------------------------------------------------------------

const FIRST_LINE = /^\/\/ HSL\* \S+/;

function withVersion(source, name) {
  if (!FIRST_LINE.test(source)) throw new Error(`${name} must start with "// HSL* <version>".`);
  return source.replace(FIRST_LINE, `// HSL* ${VERSION}`);
}

// --- Hue table ------------------------------------------------------------------

// 1024 steps keep every sRGB channel within a third of an 8-bit step of the
// library; 512 would allow 1.3 steps in the blues, where the axis is stretched.
// One table serves both directions, so they undo each other exactly.
export const TABLE_SIZE = 1024;
const BEGIN = '// BEGIN TABLES';
const END = '// END TABLES';

// The HSV hue at every 360 / TABLE_SIZE degrees of the HSL* hue, unwrapped
// so the last entry is 360.
function table(name, convert) {
  const values = Array.from({ length: TABLE_SIZE + 1 }, (_, i) =>
    i === TABLE_SIZE ? 360 : convert((i * 360) / TABLE_SIZE, { hue: 'oklab' }),
  );
  const lines = [];
  for (let i = 0; i < values.length; i += 8) {
    lines.push('  ' + values.slice(i, i + 8).map((v) => v.toFixed(4)).join(', '));
  }
  return `const float ${name}[${TABLE_SIZE + 1}] = float[](\n${lines.join(',\n')}\n);`;
}

function tables() {
  return [
    `${BEGIN} (generated by scripts/sync.js, don't edit)`,
    `const int HSL_STAR_TABLE_STEPS = ${TABLE_SIZE};`,
    '',
    '// HSV hue at every step of the HSL* (OKLab) hue.',
    table('HSL_STAR_TO_HSV_HUE', toHsvHue),
    END,
  ].join('\n');
}

// Replaces everything from the BEGIN line to the END line.
function withTable(source) {
  const start = source.indexOf(BEGIN);
  const end = source.indexOf(END);
  if (start < 0 || end < start) throw new Error(`hsl-star.glsl needs the lines "${BEGIN}" and "${END}".`);
  return source.slice(0, start) + tables() + source.slice(end + END.length);
}

// --- Files ----------------------------------------------------------------------

// What each file should contain, by path.
export function synced() {
  const read = (file) => readFileSync(file, 'utf8');
  return {
    [FILES.js]: withVersion(read(FILES.js), 'hsl-star.js'),
    [FILES.glsl]: withTable(withVersion(read(FILES.glsl), 'hsl-star.glsl')),
  };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const [file, contents] of Object.entries(synced())) writeFileSync(file, contents);
  console.log(`Wrote version ${VERSION} to hsl-star.js and hsl-star.glsl, and the hue table to hsl-star.glsl`);
}
