// Keeps the generated parts of the library files in step with their sources:
// the version from package.json in the first line of hsl-star.js and
// hsl-star.glsl, the OKLab hue table in hsl-star.glsl from hsl-star.js, so
// the shader can't drift from the library, and the tables of the two
// corrections, the reference chroma (in both) and the hue shift (in
// hsl-star.js), made by tables.js. Run it after changing the version, the
// hue axis or the construction:
//
//   npm run sync

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { toHsvHue } from '../js/hsl-star.js';
import { CHROMA_STEPS, SHIFT_SS, SHIFT_STEP, SHIFT_WS, generateTables } from './tables.js';

const path = (relative) => fileURLToPath(new URL(relative, import.meta.url));
const { version: VERSION } = JSON.parse(readFileSync(path('../package.json'), 'utf8'));
export const FILES = { js: path('../js/hsl-star.js'), glsl: path('../glsl/hsl-star.glsl') };

// --- Version --------------------------------------------------------------------

const FIRST_LINE = /^\/\/ HSL\* \S+/;

function withVersion(source, name) {
  if (!FIRST_LINE.test(source)) throw new Error(`${name} must start with "// HSL* <version>".`);
  return source.replace(FIRST_LINE, `// HSL* ${VERSION}`);
}

// --- Hue table ------------------------------------------------------------------

// 1024 steps keep every sRGB channel within a third of an 8-bit step of the
// library; 512 would allow 1.3 steps in the blues, where the axis is stretched.
// One table serves both directions, so they undo each other exactly.
export const TABLE_SIZE = 1024;
const BEGIN = '// BEGIN TABLES';
const END = '// END TABLES';

// The HSV hue at every 360 / TABLE_SIZE degrees of the HSL* hue, unwrapped
// so the last entry is 360.
const hueTable = () =>
  Array.from({ length: TABLE_SIZE + 1 }, (_, i) => (i === TABLE_SIZE ? 360 : toHsvHue((i * 360) / TABLE_SIZE, { hue: 'oklab' })));

// --- Packing for the shader -------------------------------------------------------

// Every table goes into the shader four values to a vec4, with a function
// that reads value i. Some mobile GPUs reject arrays of more than about
// 4,096 elements, floats and vec4s alike; packed, the largest table has
// 1,440. A table whose length isn't a multiple of 4 is padded with its last
// value, which is never read.
const pad = (values) => [...values, ...Array((4 - (values.length % 4)) % 4).fill(values.at(-1))];
const vec4 = (values, digits) => `vec4(${values.map((v) => v.toFixed(digits)).join(', ')})`;

// The vec4s of a table, perLine vec4s to a line, with an optional comment
// at the end of each line, comment(lineIndex).
function packedLines(values, digits, perLine, comment) {
  const padded = pad(values);
  const vecs = [];
  for (let i = 0; i < padded.length; i += 4) vecs.push(vec4(padded.slice(i, i + 4), digits));
  const lines = [];
  for (let i = 0; i < vecs.length; i += perLine) {
    const comma = i + perLine < vecs.length ? ',' : '';
    const note = comment ? ` // ${comment(lines.length)}` : '';
    lines.push(`  ${vecs.slice(i, i + perLine).join(', ')}${comma}${note}`);
  }
  return lines;
}

// A packed table and the function that reads it.
function packedTable(name, reader, values, { digits, perLine, comment }) {
  const lines = packedLines(values, digits, perLine, comment);
  const size = pad(values).length / 4;
  const array =
    lines.length === 1
      ? [`const vec4 ${name}[${size}] = vec4[](${lines[0].trim()});`]
      : [`const vec4 ${name}[${size}] = vec4[](`, ...lines, ');'];
  return [...array, `float ${reader}(int i) { return ${name}[i >> 2][i & 3]; }`].join('\n');
}

function tables() {
  const { hueShift, anchorYref } = generateTables();
  const perAnchor = SHIFT_WS.length * SHIFT_SS.length;
  if (perAnchor % 8) throw new Error('Each anchor of the hue shift must fill two lines of whole vec4s.');
  return [
    `${BEGIN} (generated by scripts/sync.js, don't edit)`,
    '// Each table is packed four values to a vec4 and read value by value',
    '// through the function below it, since some mobile GPUs reject arrays of',
    '// more than about 4,096 elements.',
    `const int HSL_STAR_TABLE_STEPS = ${TABLE_SIZE};`,
    '',
    '// HSV hue at every step of the HSL* (OKLab) hue.',
    packedTable('HSL_STAR_TO_HSV_HUE', 'hslStarToHsvHueAt', hueTable(), { digits: 4, perLine: 4 }),
    '',
    `const int HSL_STAR_CHROMA_STEPS = ${CHROMA_STEPS};`,
    '',
    "// OKLab chroma of the median hue's most vivid color at L* 0, 0.5, …, 100.",
    packedTable('HSL_STAR_REFERENCE_CHROMA', 'hslStarReferenceChromaAt', referenceChroma(), { digits: 9, perLine: 2 }),
    '',
    `const int HSL_STAR_SHIFT_ANCHORS = ${360 / SHIFT_STEP};`,
    `const float HSL_STAR_SHIFT_STEP = ${SHIFT_STEP.toFixed(1)};`,
    `const int HSL_STAR_SHIFT_NW = ${SHIFT_WS.length};`,
    `const int HSL_STAR_SHIFT_NS = ${SHIFT_SS.length};`,
    packedTable('HSL_STAR_SHIFT_WS', 'hslStarShiftWAt', SHIFT_WS, { digits: 2, perLine: 4 }),
    packedTable('HSL_STAR_SHIFT_SS', 'hslStarShiftSAt', SHIFT_SS, { digits: 2, perLine: 4 }),
    '',
    "// The luminance each anchor's white share counts from.",
    packedTable('HSL_STAR_SHIFT_YREF', 'hslStarShiftYrefAt', anchorYref, { digits: 9, perLine: 2 }),
    '',
    `// Hue shift in HSV degrees at anchor hues every ${SHIFT_STEP}°, white shares`,
    `// ${SHIFT_WS.join(', ')} and saturations ${SHIFT_SS.join(', ')},`,
    '// in the order of hsl-star.js; a line per anchor hue and half its white shares.',
    packedTable('HSL_STAR_HUE_SHIFT', 'hslStarHueShiftAt', hueShift, {
      digits: 4,
      perLine: perAnchor / 8,
      comment: (line) => {
        const half = SHIFT_WS.length / 2;
        const ws = line % 2 ? SHIFT_WS.slice(half) : SHIFT_WS.slice(0, half);
        return `${Math.floor(line / 2) * SHIFT_STEP}° w ${ws[0]} to ${ws.at(-1)}`;
      },
    }),
    END,
  ].join('\n');
}

// --- The corrections' tables -----------------------------------------------

// The reference chroma, as tables.js makes it with the hue shift.
export { CHROMA_STEPS };
export const referenceChroma = () => generateTables().referenceChroma;

// The reference chroma eight values to a line, the same in both files.
function chromaLines() {
  const values = referenceChroma();
  const lines = [];
  for (let i = 0; i < values.length; i += 8) lines.push('  ' + values.slice(i, i + 8).map((v) => v.toFixed(9)).join(', '));
  return lines;
}

// The hue shift, one line per anchor hue and white share, a value per
// saturation.
function shiftLines() {
  const { hueShift } = generateTables();
  const n = SHIFT_SS.length;
  const lines = [];
  for (let i = 0; i < hueShift.length; i += n) {
    const [k, j] = [Math.floor(i / (n * SHIFT_WS.length)), (i / n) % SHIFT_WS.length];
    const values = hueShift.slice(i, i + n).map((v) => v.toFixed(4).padStart(8)).join(', ');
    lines.push(`  ${values}, // ${k * SHIFT_STEP}° w ${SHIFT_WS[j]}`);
  }
  return lines;
}

function jsTables() {
  return [
    `${BEGIN} (generated by scripts/sync.js, don't edit)`,
    `// OKLab chroma of the median hue's most vivid color at L* 0, 0.5, …, 100.`,
    'const REFERENCE_CHROMA = [',
    ...chromaLines().map((line) => line + ','),
    '];',
    '',
    `// Hue shift in HSV degrees at anchor hues every ${SHIFT_STEP}°, white shares`,
    `// ${SHIFT_WS.join(', ')} and saturations ${SHIFT_SS.join(', ')}.`,
    'const HUE_SHIFT = [',
    ...shiftLines(),
    '];',
    END,
  ].join('\n');
}

// Replaces everything from the BEGIN line to the END line with the tables.
function withTable(source, name, tables) {
  const start = source.indexOf(BEGIN);
  const end = source.indexOf(END);
  if (start < 0 || end < start) throw new Error(`${name} needs the lines "${BEGIN}" and "${END}".`);
  return source.slice(0, start) + tables + source.slice(end + END.length);
}

// --- Files ----------------------------------------------------------------------

// What each file should contain, by path.
export function synced() {
  const read = (file) => readFileSync(file, 'utf8');
  return {
    [FILES.js]: withTable(withVersion(read(FILES.js), 'hsl-star.js'), 'hsl-star.js', jsTables()),
    [FILES.glsl]: withTable(withVersion(read(FILES.glsl), 'hsl-star.glsl'), 'hsl-star.glsl', tables()),
  };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const [file, contents] of Object.entries(synced())) writeFileSync(file, contents);
  console.log(`Wrote version ${VERSION} to hsl-star.js and hsl-star.glsl, the reference chroma to both and the hue table to hsl-star.glsl`);
}
